-- Conference Planner schema. Seed rows are inserted by SeedData (Kotlin) so a demo reset
-- can restore them exactly.

CREATE TABLE attendees (
    id           TEXT PRIMARY KEY,
    display_name TEXT NOT NULL
);

CREATE TABLE sessions (
    id         BIGINT PRIMARY KEY,
    title      TEXT    NOT NULL,
    room       TEXT    NOT NULL,
    capacity   INT     NOT NULL CHECK (capacity > 0),
    sort_order INT     NOT NULL UNIQUE
);

CREATE TABLE bookings (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id   BIGINT      NOT NULL REFERENCES sessions (id),
    attendee_id  TEXT        NOT NULL REFERENCES attendees (id),
    status       TEXT        NOT NULL CHECK (status IN ('ACTIVE', 'CANCELLED')),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    cancelled_at TIMESTAMPTZ
);
-- Invariant 2: at most one ACTIVE booking per attendee and session (database backstop).
CREATE UNIQUE INDEX bookings_one_active_per_attendee ON bookings (session_id, attendee_id) WHERE status = 'ACTIVE';
CREATE INDEX bookings_active_by_session ON bookings (session_id) WHERE status = 'ACTIVE';

-- Attendee-scoped request keys (Idempotency-Key header). A row exists only for completed,
-- committed bookings because it is written in the same transaction as the booking.
CREATE TABLE booking_requests (
    attendee_id TEXT   NOT NULL REFERENCES attendees (id),
    request_key TEXT   NOT NULL,
    session_id  BIGINT NOT NULL,
    booking_id  BIGINT REFERENCES bookings (id),
    PRIMARY KEY (attendee_id, request_key)
);

-- Outbox: one pending confirmation per accepted booking, written in the booking transaction.
CREATE TABLE confirmations (
    booking_id   BIGINT PRIMARY KEY REFERENCES bookings (id),
    delivery_key TEXT        NOT NULL UNIQUE,
    status       TEXT        NOT NULL CHECK (status IN ('PENDING', 'DELIVERED')),
    attempts     INT         NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    delivered_at TIMESTAMPTZ
);

CREATE TABLE delivery_attempts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id   BIGINT      NOT NULL REFERENCES bookings (id),
    attempt_no   INT         NOT NULL,
    delivery_key TEXT        NOT NULL,
    outcome      TEXT        NOT NULL CHECK (outcome IN ('ACKNOWLEDGED', 'DUPLICATE_ACKNOWLEDGED', 'TIMEOUT')),
    attempted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Fake gateway state. Owned by FakeGateway, which always writes it in its own transaction.
CREATE TABLE gateway_messages (
    delivery_key TEXT PRIMARY KEY,
    recipient    TEXT        NOT NULL,
    body         TEXT        NOT NULL,
    accepted_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE gateway_settings (
    id                    INT PRIMARY KEY CHECK (id = 1),
    lose_acknowledgements BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE demo_activity (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    happened_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    kind        TEXT NOT NULL,
    message     TEXT NOT NULL
);
