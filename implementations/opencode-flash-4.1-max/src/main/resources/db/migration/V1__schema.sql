create table sessions (
    id       bigint primary key,
    title    text    not null,
    room     text    not null,
    capacity integer not null check (capacity > 0)
);

create table bookings (
    id           bigint generated by default as identity primary key,
    session_id   bigint      not null references sessions (id),
    attendee     text        not null,
    status       text        not null check (status in ('ACTIVE', 'CANCELLED')),
    created_at   timestamptz not null default now(),
    cancelled_at timestamptz
);

-- Invariant 2: at most one ACTIVE booking per attendee and session, enforced by the
-- database so it also holds across application processes.
create unique index ux_bookings_active_attendee_session
    on bookings (session_id, attendee)
    where status = 'ACTIVE';

create index ix_bookings_attendee_active on bookings (attendee) where status = 'ACTIVE';

-- Attendee-scoped request keys: replaying a completed request returns its original
-- booking; a row is retained after cancellation so a replay never rebooks.
create table idempotency_keys (
    attendee     text        not null,
    request_key  text        not null,
    payload_hash text        not null,
    booking_id   bigint references bookings (id),
    created_at   timestamptz not null default now(),
    primary key (attendee, request_key)
);

-- One pending confirmation per booking. The delivery key is stable for the lifetime
-- of the booking (derived from the booking id), so retries always reuse it.
create table notifications (
    delivery_key    text primary key,
    booking_id      bigint      not null unique references bookings (id),
    status          text        not null check (status in ('PENDING', 'ACKNOWLEDGED')),
    attempts        integer     not null default 0,
    created_at      timestamptz not null default now(),
    acknowledged_at timestamptz
);

create table delivery_attempts (
    id             bigint generated by default as identity primary key,
    delivery_key   text        not null,
    attempt_number integer     not null,
    outcome        text        not null,
    detail         text,
    created_at     timestamptz not null default now()
);

-- Tables owned by the fake gateway simulator. They are written through a separate
-- connection pool so gateway acceptance is never rolled back by the sender.
create table gateway_messages (
    delivery_key text primary key,
    booking_id   bigint      not null,
    body         text        not null,
    accepted_at  timestamptz not null default now()
);

create table demo_activity (
    id         bigint generated by default as identity primary key,
    kind       text        not null,
    message    text        not null,
    created_at timestamptz not null default now()
);

create table demo_controls (
    name  text primary key,
    value text not null
);
